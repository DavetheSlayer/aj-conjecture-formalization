def source_path(rel: str) -> str:
    """Path from the project root of a file named in `DECLS`/`STATEMENTS` (the solution is at the
    root, the library below `Proofs/`) or of the configuration."""
    return rel if rel in (f"{SOLUTION}.lean", CONFIG) else f"{SRC}/{rel}"


def read(rel: str) -> str:
    return (ROOT / source_path(rel)).read_text(encoding="utf-8")


def strip_comments(text: str, name: str) -> str:
    """Remove block comments and docstrings (nested ones included) and line comments."""
    out, k, depth, start = [], 0, 0, 0
    while k < len(text):
        if text.startswith("/-", k):
            if depth == 0:
                out.append(text[start:k])
            depth += 1
            k += 2
        elif text.startswith("-/", k) and depth > 0:
            depth -= 1
            k += 2
            start = k
        else:
            k += 1
    assert depth == 0, (name, "unterminated comment")
    out.append(text[start:])
    lines = []
    for ln in "".join(out).splitlines():
        assert '"' not in ln or "--" not in ln, (name, "string and comment on one line", ln)
        i = ln.find("--")
        lines.append(ln if i < 0 else ln[:i])
    return "\n".join(lines)


class Decl:
    def __init__(self, rel: str, name: str, lines: list[str], ctx: tuple, private: bool,
                 bad: list[str]):
        self.rel, self.name, self.lines, self.ctx = rel, name, lines, ctx
        self.private, self.bad = private, bad


def instance_name(head: str) -> str | None:
    """Lean's automatic name of an anonymous instance `instance : C A B` (simple cases)."""
    m = re.match(r"(?:@\[[^\]]*\]\s*)?(?:noncomputable\s+)?instance\s*(?:\(priority[^)]*\)\s*)?"
                 r"((?:\[[^\]]*\]\s*|\{[^}]*\}\s*)*):\s*(.*?)(?::=|where|$)", head)
    if not m:
        return None
    ids = re.findall(r"[^\W\d][\w'.₀-₉ℚℂℤℝ]*", m.group(2))
    return "inst" + "".join(i.split(".")[-1][:1].upper() + i.split(".")[-1][1:] for i in ids)


def decl_head(line: str) -> tuple[str | None, bool]:
    """(declared name or None, private?) if `line` starts a declaration at column 0."""
    words = line.split()
    private = False
    while words and (words[0] in MODIFIERS or words[0].startswith("@[")):
        if words[0].startswith("@[") and not words[0].endswith("]"):
            while words and not words[0].endswith("]"):
                words = words[1:]
        private |= words[0] == "private"
        words = words[1:]
    if not words or words[0] not in KEYWORDS:
        return None, private
    if words[0] == "instance" and len(words) > 3 and words[1] == "(priority" and \
            words[3].endswith(")") and not words[4].startswith((":", "[", "{", "(")):
        return words[4], private
    if words[0] == "instance" and (len(words) < 2 or words[1].startswith((":", "[", "{", "("))):
        return instance_name(line[line.index("instance"):]), private
    return words[1], private


def declarations(rel: str) -> list[Decl]:
    """The top-level declarations of `rel.lean` in file order, each with its code lines (prefix
    lines, the line starting it at column 0, the indented lines after it) and its context: the
    `open` and `variable` lines in scope and the namespaces below `AJConjecture`."""
    text = read(f"{rel}.lean")
    for ln in text.splitlines():
        if ln.startswith("import "):
            assert ln == "import Mathlib" or ln.startswith(
                ("import AJConjecture", "import AJFamily", "import AJHandoff", "import AJTwist",
                 "import SolutionDefs")), (rel, ln)
    lines = [ln.rstrip() for ln in strip_comments(text, rel).splitlines()
             if ln.strip() and not ln.startswith("import ")]
    decls: list[Decl] = []
    # scope: [kind, name, opens, variables, unsupported]
    scopes: list[list] = [["file", "", [], [], []]]
    current: list[str] | None = None
    pending: list[str] = []
    for ln in lines:
        if ln[0] == " ":
            assert current is not None, (rel, "indented line outside a declaration", ln)
            current.append(ln)
            continue
        current = None
        words = ln.split()
        if words[0] == "namespace":
            scopes.append(["namespace", words[1], [], [], []])
        elif words[:2] == ["noncomputable", "section"] or words[0] == "section":
            rest = words[2:] if words[0] == "noncomputable" else words[1:]
            scopes.append(["section", rest[0] if rest else "", [], [], []])
        elif words[0] == "end":
            kind, nm = scopes.pop()[:2]
            assert nm == (words[1] if len(words) > 1 else ""), (rel, "unbalanced", ln)
        elif words[0] in ("open", "set_option") and ln.endswith(" in"):
            pending.append(ln)
        elif ln.startswith("@[") and ln.endswith("]"):
            pending.append(ln)
        elif words[0] == "open":
            scopes[-1][2].append(ln)
        elif words[0] in ("variable", "universe"):
            current = [ln]
            scopes[-1][3].append(current)
        else:
            name, private = decl_head(ln)
            if name is None:
                assert words[0] in UNSUPPORTED or words[0].startswith("#"), (rel, ln)
                scopes[-1][4].append(ln)
                continue
            ns = [s[1] for s in scopes if s[0] == "namespace"]
            assert ns[:1] == ["AJConjecture"], (rel, ln)
            opens = tuple(o for s in scopes for o in s[2])
            variables = tuple("\n".join(v) for s in scopes for v in s[3])
            bad = [b for s in scopes for b in s[4]]
            current = pending + [ln]
            pending = []
            decls.append(Decl(rel, ".".join(ns[1:] + [name]), current,
                              (tuple(ns[1:]), opens, variables), private, bad))
    assert not pending, (rel, "dangling prefix", pending)
    assert [s[0] for s in scopes] in (["file"], ["file", "section"]), (rel, "unclosed scope")
    return decls


def select(rel: str, names: list[str] | str) -> list[Decl]:
    decls = declarations(rel)
    if names == "*":
        out = decls
    else:
        out = []
        for n in names:
            found = [d for d in decls if d.name == n]
            assert len(found) == 1, (rel, "missing or declared twice", n)
            out.append(found[0])
        pos = {id(d): i for i, d in enumerate(decls)}
        assert [pos[id(d)] for d in out] == sorted(pos[id(d)] for d in out), (rel, "file order")
    for d in out:
        assert not d.private, (rel, d.name, "private declaration")
        assert not d.bad, (rel, d.name, "unsupported command in scope", d.bad)
        assert not any(re.search(r"\b(sorry|admit)\b", ln) for ln in d.lines), (rel, d.name)
    return out


def emit_group(decls: list[Decl]) -> list[str]:
    """Emit consecutive declarations, each run with the same context wrapped in one section."""
    out: list[str] = []
    i = 0
    while i < len(decls):
        ctx = decls[i].ctx
        j = i
        while j < len(decls) and decls[j].ctx == ctx:
            j += 1
        ns, opens, variables = ctx
        out += ["section"] + list(opens) + list(variables) + [f"namespace {n}" for n in ns]
        for d in decls[i:j]:
            out += d.lines
        out += [f"end {n}" for n in reversed(ns)] + ["end"]
        i = j
    return out


def base(rel: str) -> str:
    return rel.rsplit("/", 1)[-1]


def module_name(rel: str) -> str:
    return f"{CHALLENGE_DIR}.C_{base(rel)}"


def source_imports(rel: str) -> list[str]:
    """The library files imported by `rel.lean` (relative paths without `.lean`)."""
    return [ln.split()[1].replace(".", "/") for ln in read(f"{rel}.lean").splitlines()
            if ln.startswith("import ") and ln.split()[1] != "Mathlib"]


_ANC: dict[str, set[str]] = {}


def ancestors(rel: str) -> set[str]:
    """The library files that `rel.lean` imports, transitively."""
    if rel not in _ANC:
        out: set[str] = set()
        for r in source_imports(rel):
            out |= {r} | ancestors(r)
        _ANC[rel] = out
    return _ANC[rel]


def minimal(rels: set[str]) -> list[str]:
    """`rels` without the files that another file of `rels` imports, in `DECLS` order."""
    keep = {r for r in rels if not any(r in ancestors(q) for q in rels if q != r)}
    return [r for r, _ in DECLS if r in keep]


def challenge_module(rel: str, names: list[str] | str) -> str:
    copied = {r for r, _ in DECLS}
    imports = ["Mathlib"] + [module_name(r) for r in minimal(copied & ancestors(rel))]
    body = emit_group(select(rel, names))
    return ("\n".join(f"import {m}" for m in imports) + "\n\n"
            + MODULE_DOC.format(path=source_path(f"{rel}.lean"))
            + "\n\nnoncomputable section\n\nnamespace AJConjecture\n\n" + "\n".join(body)
            + "\n\nend AJConjecture\n")


def statement(rel: str, name: str) -> list[str]:
    """The declaration of theorem `name` in `rel`, cut at the `:=` of its proof, with `sorry`."""
    d = select(rel.removesuffix(".lean"), [name])[0]
    assert d.lines[len([ln for ln in d.lines if ln.endswith(" in") or ln.startswith("@[")])]\
        .startswith("theorem "), (rel, name, "not a theorem")
    text = "\n".join(d.lines)
    depth, stop = 0, None
    for k, ch in enumerate(text):
        if ch in "([{⟨⦃":
            depth += 1
        elif ch in ")]}⟩⦄":
            depth -= 1
        elif depth == 0 and text.startswith(" :=", k):
            stop = k
            break
    assert stop is not None, (rel, name, "no proof")
    d.lines = (text[:stop] + " := by\n  sorry").splitlines()
    return emit_group([d])


def generate() -> dict[str, str]:
    """Path (relative to the root) -> content, for every challenge module."""
    bases = [base(r) for r, _ in DECLS]
    assert len(bases) == len(set(bases)), "two source files with the same base name"
    out = {f"{CHALLENGE_DIR}/C_{base(rel)}.lean": challenge_module(rel, names)
           for rel, names in DECLS}
    copied = {r for r, _ in DECLS}
    imports = ["Mathlib"] + [module_name(r) for r in minimal(copied)]
    stmts = "".join("\n" + "\n".join(statement(rel, n)) + "\n" for rel, n in STATEMENTS)
    out[TARGET] = ("\n".join(f"import {m}" for m in imports) + "\n\n" + ROOT_DOC
                   + "\n\nnoncomputable section\n\nnamespace AJConjecture\n" + stmts
                   + "\nend AJConjecture\n")
    return out


def check_config() -> list[str]:
    cfg = json.loads(read(CONFIG))
    want = ["AJConjecture." + n for _, n in STATEMENTS]
    errors = []
    if cfg.get("challenge_module") != TARGET.removesuffix(".lean"):
        errors.append(f"challenge_module is not {TARGET.removesuffix('.lean')}")
    if cfg.get("solution_module") != SOLUTION:
        errors.append(f"solution_module is not {SOLUTION}")
    if sorted(cfg.get("theorem_names", [])) != sorted(want):
        errors.append(f"theorem_names differ from {want}")
    if sorted(cfg.get("permitted_axioms", [])) != sorted(["propext", "Quot.sound",
                                                          "Classical.choice"]):
        errors.append("permitted_axioms are not the three standard axioms")
    return errors


def main(argv: list[str]) -> int:
    global ROOT
    if "--root" in argv:
        ROOT = pathlib.Path(argv[argv.index("--root") + 1]).resolve()
    files = generate()
    if "--check" in argv:
        errors = [f"{path} is out of date" for path, text in files.items()
                  if not (ROOT / path).exists() or (ROOT / path).read_text(encoding="utf-8") != text]
        errors += [f"{p.relative_to(ROOT)} is not generated (stray file)"
                   for p in sorted((ROOT / CHALLENGE_DIR).glob("**/*.lean"))
                   if str(p.relative_to(ROOT)) not in files]
        errors += [f"{CONFIG}: {e}" for e in check_config()]
        for e in errors:
            print(e)
        if errors:
            print("run tools/make_challenge.py")
            return 1
        print(f"{len(files)} challenge modules match the source declarations and statements; "
              f"{CONFIG} names the {len(STATEMENTS)} theorems")
        return 0
    (ROOT / CHALLENGE_DIR).mkdir(exist_ok=True)
    for p in (ROOT / CHALLENGE_DIR).glob("C_*.lean"):
        if str(p.relative_to(ROOT)) not in files:
            p.unlink()
    for path, text in files.items():
        (ROOT / path).write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} challenge modules "
          f"({sum(len(t.splitlines()) for t in files.values())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

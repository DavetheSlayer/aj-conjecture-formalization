#!/usr/bin/env python3
"""Generate (or check) the challenge for `lake comparator`.

The challenge is a set of Lean modules that import only Mathlib and one another: one module
`Challenge/C_<name>.lean` for every source file `Proofs/.../<name>.lean` that declarations are
copied from, and the root `Challenge.lean`, which holds the statements of the release
theorems (`STATEMENTS`, with `sorry` in place of their proofs). Every declaration they depend on is
copied verbatim (without docstrings and comments) from its source file into that file's challenge
module, in file order. The challenge contains declarations only: no metaprogramming, no options.

* `DECLS` lists, per source file (path below `Proofs/`, in import order), the declarations to copy:
  every declaration of the library reachable from the statements (through types, values,
  constructors and recursor rules, as `lake comparator` follows them), including the theorems whose
  proofs occur inside a definition (e.g. the proof fields of a structure value) and the
  declarations that create an auxiliary constant used by another one (a shared `match_` or
  `_proof_`); `"*"` copies a whole file. The list is computed from the built library by
  `tools/closure_decls.py`, which collects this closure and maps each constant to the declaration
  creating it (`closure_decls.py --write` rewrites the list, without `--write` it checks it); a
  missing entry makes the challenge fail to elaborate, a wrong one fails the identity check
  (`compare_reach.py`).
* One module per source file: Lean shares auxiliary declarations (the `_proof_i` lemmas of nested
  proofs, e.g. the `Nat.AtLeastTwo` proof of a numeral `2` in a ring, and identical `match_`
  definitions) between the declarations of one module through caches that start empty in every
  module. With the library's module boundaries the challenge gets the library's auxiliary
  declarations. A challenge module imports the challenge modules of the copied files among its
  source file's (transitive) imports, reduced to a minimal list; so its environment contains no
  declaration that the source file could not see.
* Each declaration is copied with its context in its source file: the `open` and `variable`
  lines in scope, enclosing namespaces below `AJConjecture`, and its `open … in` /
  `set_option … in` / attribute prefix lines. Derived instances come with their `deriving`
  clause. A declaration that is `private`, or that sits in a scope with a `notation`, `attribute`,
  `local`/`scoped` command, is rejected: a copy could not be identical.
* Definitions of the library whose bodies use `private` lemmas cannot be copied (a private name
  contains its module). For the theorems about them, `Proofs/SolutionDefs.lean` has public
  copies of those lemmas and replacement definitions (`…R`) that differ from the library's only in
  their proof terms; the release theorems in `Solution.lean` are stated with them.

The statements at the end are copied from their source files: library theorems whose statements
mention only data (copied as they are) and the release theorems of `Solution.lean`.

    python3 tools/make_challenge.py            # rewrite the challenge modules
    python3 tools/make_challenge.py --check    # exit 1 if any of them is out of date
    python3 tools/make_challenge.py --root DIR [--check]   # project root other than ..

`--check` regenerates every challenge module and compares it with the file byte for byte (and
reports stray files in `Challenge/`), so it verifies that every declaration of the
challenge is a verbatim copy of the current source declaration, every import list follows the
library's imports, and every statement is the current statement in its source file; it also
checks that `comparator.json` names exactly the statements' theorems. `lake comparator`
then checks that every constant the statements depend on is identical in the challenge and in the
solution (module `Solution`).
"""
